/** Кратко цитиране за подсказка: „ESC 2026 СН; AHA/ACC 2025“. */
export function cite(...ids) {
  return ids.map(id => GUIDELINES[id]?.short || id).join('; ');
}

/** Насоките по теми, най-новите отгоре — за списъка в настройките. */
export function guidelinesByTopic() {
  const out = {};
  for (const [id, gl] of Object.entries(GUIDELINES)) (out[gl.topic] ||= []).push({ id, ...gl });
  for (const list of Object.values(out)) list.sort((a, b) => b.year - a.year || a.org.localeCompare(b.org));
  return Object.keys(TOPICS).filter(t => out[t]).map(t => ({ topic: t, label: TOPICS[t], items: out[t] }));
}
