/**
 * Чеклистът за родителя до 1 година.
 * input: { birthDate, gestWeeks, asOf, chronological (навършени месеци по календара) }.
 * Връща { corrected, months, ages: [{ month, label, date, status, domains, tips }], current, next, actEarly, rules }.
 */
export function parentChecklist({ birthDate, gestWeeks = null, chronological = 0 } = {}) {
  const age = growthAge(chronological, gestWeeks);
  const months = age.months; // при недоносено — коригираната възраст
  const shift = isPreterm(Number(gestWeeks)) ? Math.round((40 - Number(gestWeeks)) * 7) : 0;
  const reached = PARENT_AGES.filter(m => m <= months + 0.5);
  const current = reached.length ? reached[reached.length - 1] : null;
  const next = PARENT_AGES.find(m => m > months + 0.5) || null;
  const ages = PARENT_AGES.map(m => {
    const cp = CHECKPOINTS.find(c => c.ageMonths === m);
    return {
      month: m,
      label: m === 12 ? '1 година' : `${m} месеца`,
      date: birthDate ? addDays(birthDate, Math.round(m * 30.4375) + shift) : null,
      status: m === current ? 'now' : m === next ? 'next' : m < (current ?? 0) ? 'past' : 'later',
      domains: DOMAIN_ORDER.map(d => ({
        key: d, label: DEV_DOMAINS[d].label, icon: DEV_DOMAINS[d].icon,
        items: cp.items.filter(it => it.domain === d).map(it => ({ id: it.id, text: it.bg })),
      })).filter(d => d.items.length),
      tips: PARENT_TIPS[m],
    };
  });
  return {
    corrected: age.corrected, months: Math.round(months * 100) / 100,
    ages, current, next,
    actEarly: ACT_EARLY,
    rules: DEVELOPMENT_RULES,
  };
}
